#!/usr/bin/env python3
"""Generate tls_sites.h: every instruction in cm0102.exe 3.9.68 that addresses one of the per-thread globals.

    python3 -I tools/tls_sites.py /path/to/cm0102.exe > src/tls_sites.h

Needs objdump (binutils). Each site is (address, length, global index, offset of the disp32 or moffs32 in
the instruction, original bytes); tls.c turns each into a jump to a thunk that runs the same instruction
with an fs: override, addressing the global's slot in the TEB (TlsSlots) instead. docs/par-matches.md.
"""
import re
import struct
import subprocess
import sys

# (address, name): the globals that become per-thread. Each must only ever be addressed directly (no
# pointer taken), as a dword.
GLOBALS = [
    (0xDE1F60, "random(n): table position"),
    (0xDE1F5C, "random(n): offset"),
    (0xAD6C30, "CRT rand: holdrand"),
    (0xB67A64, "0x6bd760 scratch"),
    (0xADAE10, "lookup cache (0x4a4850)"),
    (0xADAE14, "lookup cache (0x49ee70)"),
    (0xADAE18, "lookup cache (0x49ee70)"),
    (0xB679FC, "sort context (0x6827d0)"),
    (0xB67A00, "sort comparator (0x6827d0)"),
]

exe = sys.argv[1]
data = open(exe, "rb").read()
TEXT_VA, TEXT_OFF = 0x401000, 0x1000  # .text: file offset == RVA

out = subprocess.run(["objdump", "-d", "-M", "intel", "--insn-width=16", "--start-address=0x401000", "--stop-address=0x967000", exe],
                     capture_output=True, text=True, check=True).stdout
line_re = re.compile(r"^\s*([0-9a-f]+):\s+((?:[0-9a-f]{2} )+)\s*(.*)$")
insns = []
for line in out.splitlines():
    m = line_re.match(line)
    if m:
        insns.append((int(m.group(1), 16), bytes.fromhex(m.group(2).replace(" ", "")), m.group(3)))

sites = []
for addr, raw, text in insns:
    for gi, (g, _) in enumerate(GLOBALS):
        pat = struct.pack("<I", g)
        k = raw.find(pat)
        if k < 0:
            continue
        if raw.find(pat, k + 1) >= 0 or f"{g:#x}" not in text:
            sys.exit(f"{addr:#x}: ambiguous instruction {text}")
        # allowed forms: moffs (A0-A3) or modrm with mod=00 rm=101 (disp32 only), no prefixes except 66
        body = raw[1:] if raw[0] == 0x66 else raw
        pre = len(raw) - len(body)
        ok = body[0] in (0xA0, 0xA1, 0xA2, 0xA3) and k == pre + 1
        if not ok:
            op_len = 2 if body[0] == 0x0F else 1
            modrm = body[op_len]
            ok = (modrm & 0xC7) == 0x05 and k == pre + op_len + 1
        if not ok:
            sys.exit(f"{addr:#x}: unsupported form {raw.hex()} {text}")
        if len(raw) < 5:
            sys.exit(f"{addr:#x}: too short to patch: {text}")
        sites.append((addr, len(raw), gi, k, raw, text))

print("/* Generated by tools/tls_sites.py from cm0102.exe 3.9.68: instructions addressing per-thread globals. */")
print(f"#define TLS_NGLOBALS {len(GLOBALS)}")
print("static const DWORD tls_globals[TLS_NGLOBALS] = {" + ", ".join(f"{g:#x}" for g, _ in GLOBALS) + "};")
print(f"#define TLS_NSITES {len(sites)}")
print("static const struct tls_site { DWORD addr; BYTE len, global, disp; BYTE bytes[12]; } tls_sites[TLS_NSITES] = {")
for addr, n, gi, k, raw, text in sites:
    print(f"    {{{addr:#x}, {n}, {gi}, {k}, {{{', '.join(f'0x{b:02x}' for b in raw)}}}}}, /* {text} */")
print("};")
print(f"/* {len(sites)} sites */", file=sys.stderr)
